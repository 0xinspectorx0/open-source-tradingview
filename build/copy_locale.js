// Copy the Turkish locale shipped with Vela 0.9.3 (Apache-2.0; see THIRD_PARTY_NOTICES.md).
const fs = require('fs'), path = require('path');
const source = fs.readFileSync(require.resolve('@luxalgo/vela/locales/tr'), 'utf8');
const match = source.match(/var tr_default = (\{[\s\S]*?\});\s*\/\/ src\/locales\/tr\.ts/);
if (!match) throw new Error('Vela Turkish locale format changed');
const messages = JSON.parse(match[1]);
fs.writeFileSync(path.join(__dirname,'../hub/vela_locale_tr.js'), '// Vela Turkish locale, Apache-2.0. Generated by build/copy_locale.js.\nwindow.VelaTurkish = ' + JSON.stringify(messages, null, 2) + ';\n');
